"""주소 탐지기 — 시/도명을 기준으로 지번·도로명 주소 패턴을 찾는다.

동작 원리:
1. 시/도명(사전 기반, 신구 행정명 모두 포함)이 나오면 후보로 삼는다.
2. 뒤에 시/군/구(2단계까지), 읍/면/동/리 또는 도로명, 번지(건물번호), 건물명+동/호가
   순서대로 이어지는지 확인하고 이어지는 만큼 구간을 넓힌다. 읍·면 뒤의 리·도로명("해남읍 중앙1로 330")과
   이름에 숫자가 든 동·도로명("신림2동", "을지로3가", "센텀2로")도 한 구간으로 잇는다(#423).
3. 매칭된 구성 요소가 많을수록(시/도만 vs 동/번지/건물까지 전부) 확신도를 높인다.
   "서울특별시청"처럼 시/도명이 다른 단어의 일부일 뿐이면 매칭하지 않는다.
4. 시/도 없이 시/군으로 시작하는 주소("성남시 분당구 정자동 45-6")도 별도 앵커로 잡는다.
   시/군 뒤에 구·동/읍/면/리가 이어질 때만(지역 언급·조사 배제) 낮은 확신도(0.4~)로 잡는다(이슈 #68).
5. 시/도를 줄여 쓴 주소("서울 강남구 테헤란로 123")도 잡는다(#396). 일상 문서는 정식명보다
   축약형을 더 자주 쓴다. "서울 사람", "경기 침체"처럼 지역 이름으로만 쓰인 문장을 막으려고
   축약형 바로 뒤에 시/군/구가 오고, 그 뒤에 동/읍/면/리나 도로명까지 이어질 때만 인정한다.

구간을 끝까지 넓히는 게 핵심이다. 시/도만 가리고 "월드컵로237길 49 ..."를 남기면
개인정보 가치가 가장 낮은 부분만 가린 셈이라 사실상 유출이다(이슈 #66).
"""

from __future__ import annotations

import re

from maskingtape.detectors.base import Detector
from maskingtape.types import Detection

_PROVINCES = [
    "서울특별시",
    "부산광역시",
    "대구광역시",
    "인천광역시",
    "광주광역시",
    "대전광역시",
    "울산광역시",
    "세종특별자치시",
    "경기도",
    "강원특별자치도",
    "강원도",
    "충청북도",
    "충청남도",
    "전북특별자치도",
    "전라북도",
    "전라남도",
    "경상북도",
    "경상남도",
    "제주특별자치도",
    "제주도",
]

# 긴 이름부터 매칭해야 "전라북도"가 "전북특별자치도" 매칭을 가로채지 않는다.
_PROVINCE_RE = "|".join(sorted(_PROVINCES, key=len, reverse=True))

# 시/도 축약형(#396). 모두 두 글자라 정렬이 필요 없다.
# 세종은 넣지 않았다. 세종특별자치시는 시/군/구 단계 없이 바로 동·읍·면이 와서 아래의
# "축약형 뒤에 시/군/구" 조건을 만족할 수 없고, 조건을 풀면 "세종 대왕로" 같은 표현과
# 구분이 어려워진다. 정식명 "세종특별자치시 …"는 _ADDR_RE가 잡는다.
_PROVINCE_ABBR = [
    "서울", "부산", "대구", "인천", "광주", "대전", "울산",
    "경기", "강원", "충북", "충남", "전북", "전남", "경북", "경남", "제주",
]

# 시/도명 뒤에 공백 없이 붙는 조사(에/로/의/은/는/이/가/에서/으로/까지 …)는 정상 한국어 표기라
# 시/도만으로도 주소로 인정해야 한다("본사는 서울특별시에 있다" → 주소 '서울특별시'). 반면 조사가
# 아닌 한글이 붙으면 다른 단어의 일부다("서울특별시청"의 '청") — 이건 제외한다(#196).
# 계사(이다)의 활용형("주소는 X입니다/예요/였…")도 자기 주소를 설명하는 흔한 표기라 허용한다(#248).
# 이-로 시작하는 활용형(이다·이에요·이라·이었…)은 아래 '이'가 이미 커버한다.
# 긴 조사(에서·으로·까지·입니다)부터 둬야 "에서"가 "에"로 잘리지 않는다.
# 아래 동/도로명 자리에서 낱말이 끝났는지 판정할 때도 이 목록을 쓴다(#423).
_JOSA = "입니다|입니까|예요|였|에서|에게|으로|까지|부터|처럼|보다|조차|마저|밖에|마다|한테|의|에|로|은|는|이|가|을|를|과|와|도|만"

# 시/도 앵커와 시/군 앵커가 공유하는 꼬리. 시/군/구·동·번지·건물을 이어붙인다.
# 시/군/구는 두 단계까지 이어진다 — "성남시 분당구", "수원시 영통구".
_GU = r"(?:\s(?P<gu>[가-힣]{1,10}[시군구]))?"
_GU2 = r"(?:\s(?P<gu2>[가-힣]{1,10}[군구]))?"

# --- 동/도로명 자리(#423) ---
# 이 자리에서 구간이 끊기면 뒤따르는 도로명·건물번호가 원문 그대로 남는다(부분 유출).
# 예전 규칙은 동/읍/면/리를 먼저 찾고 한 토막만 받아서 이런 입력이 중간에서 끊겼다.
#   "해남읍 중앙1로 330"   읍 뒤에 도로명이 올 자리가 없음
#   "대동로 12"            '대동'(동으로 끝남)에서 멈춤
#   "센텀2로 25"           도로명 안의 숫자를 받지 않음
# 그래서 더 구체적인 해석부터 차례로 시도하고, 전부 실패하면 예전 규칙으로 돌아간다.
# 앞의 해석이 성립할 때는 예전 규칙이 잡던 구간보다 짧게 끝나지 않도록 짰다. 조사 목록에 동/읍/면/리로
# 끝나는 말이 없고, 도로명 뒤에서는 '으로'를 조사로 보지 않기 때문이다(아래 _ROAD_END). 예전 코드와
# 무작위 입력 6만 건을 비교해 덜 가리는 입력이 없음을 확인했다.

# 번지(건물번호) 숫자 모양. 더 긴 숫자열을 거르는 가드 (?![\d-])는 쓰는 곳에서 붙인다.
_BUNJI = r"\d{1,4}(?:-\d{1,4})?"
# 바로 뒤에 번지가 오는지 미리 본다. 번지가 뒤따르면 앞 낱말은 도로명이 확실하다.
# 주민등록번호·전화번호처럼 더 긴 숫자열은 번지가 아니므로 근거로 삼지 않는다.
_BUNJI_AHEAD = r"(?=\s" + _BUNJI + r"(?![\d-]))"
# 낱말 끝 판정. 뒤에 조사만 붙었거나("역삼동에서") 한글·숫자가 더 이어지지 않아야 낱말이 끝난 것이다.
_END = r"(?=(?:" + _JOSA + r")?(?![가-힣0-9]))"
# 도로명. 이름 중간에 숫자가 들기도 한다("센텀2로", "올림픽로35가길").
# 조사 '으로'의 '로'를 도로명 끝으로 읽으면 "역삼동으로 12명"이 도로명+번지가 되므로 '으로'로 끝나는 낱말은 뺀다.
_ROAD = r"[가-힣][가-힣0-9]{0,9}(?<!으)(?:로|길)(?:\s?\d{1,4}번?길)?"
# 도로명 뒤의 낱말 끝 판정. 도로명은 '로'(받침 없음)나 '길'(ㄹ 받침)로 끝나 조사 '으로'가 아니라 '로'가 붙는다.
# 그래서 여기서는 '으로'를 조사로 보지 않는다. "테헤란로으로 12"처럼 어긋난 표기를 도로명+조사로 끊으면
# 예전 규칙보다 구간이 짧아지므로, 이런 낱말은 맨 끝의 예전 규칙에 넘긴다.
_ROAD_END = r"(?=(?:" + "|".join(j for j in _JOSA.split("|") if j != "으로") + r")?(?![가-힣0-9]))"
# 동/읍/면/리. 행정동은 숫자가 붙고("신림2동"), 도심에는 "을지로3가" 같은 N가 동이 있다.
_DONG = r"[가-힣]{1,10}(?:\d{1,2}(?:동|리|가)|동|읍|면|리)"
# 두 토막짜리 자리.
# - 읍·면 뒤의 리: 군 지역 지번주소의 표준 형식("양평읍 양근리 123")
# - 읍·면·동 뒤의 도로명: 군 지역 도로명주소의 표준 형식("해남읍 중앙1로 330")과
#   도로명주소에 동을 덧붙여 쓰는 표기("역삼동 테헤란로 123")
# 도로명은 번지가 뒤따를 때만 붙인다. "역삼동 근처로 이사"의 '근처로'까지 삼키지 않게 하려는 것이다.
_TWO_PART = (
    r"[가-힣]{1,10}(?:읍|면)\s[가-힣]{1,10}\d{0,2}리" + _END
    + r"|[가-힣]{1,10}(?:\d{1,2}동|동|읍|면)\s" + _ROAD + _BUNJI_AHEAD
)
# 위에서부터 먼저 성립하는 해석 하나를 쓴다. 순서가 곧 우선순위다.
_LOCALITY = (
    r"(?:" + _TWO_PART + r")"
    # 번지가 뒤따르는 도로명. 조사 '로'와 도로명 끝 '로'는 모양이 같아서 이걸 동 해석보다
    # 먼저 둬야 "대동로 12"를 '대동'+조사 '로'로 끊지 않는다.
    + r"|" + _ROAD + _BUNJI_AHEAD
    # 낱말이 끝나는 동/읍/면/리. "역삼동으로 이사", "사우리로 이사"(조사 '로')가 여기서 잡힌다.
    + r"|" + _DONG + _END
    # 번지 없이 낱말이 끝나는 도로명("대동로에서", "한누리대로에").
    + r"|" + _ROAD + _ROAD_END
    # 위가 전부 실패하면 예전 규칙. "역삼동쪽으로"처럼 조사 목록 밖의 말이 붙은 경우다.
    + r"|[가-힣]{1,10}(?:동|읍|면|리)|[가-힣]{1,10}(?:로|길)(?:\s?\d{1,4}번?길)?"
)

_TAIL = (
    # 지번은 동/읍/면/리로 끝나지만, 도로명은 "월드컵로237길"처럼 가지번호가 공백 없이 붙는다.
    r"(?:\s(?P<dong>" + _LOCALITY + r"))?"
    # 번지 뒤에 숫자·하이픈이 더 이어지면 번지가 아니라 더 긴 숫자열(주민등록번호·전화번호)의
    # 일부다. 그걸 삼키면 주소 구간이 그 번호와 겹쳐 번호 탐지를 방해하므로 여기서 끊는다.
    # "123번지"처럼 풀어쓰면(리터럴 '번지') 뒤 건물명·호수 체인이 끊겨 세대정보가 새므로(#340)
    # 숫자 뒤 선택적 '번지'를 허용한다 — (?![\d-]) 가드 뒤라 긴 숫자열 배제는 그대로다.
    r"(?:\s(?P<bunji>" + _BUNJI + r")(?![\d-])(?:번지)?(?:\s?호)?)?"
    # 건물명과 동/호까지 가려야 세대가 특정되지 않는다 — "더샵아파트 123동 1241호".
    # 건물명이 없어도("... 49 123동 1241호") 동/호는 각각 독립적으로 이어붙인다.
    # 번지와 건물 사이에 콤마가 끼는 표기("판교로 456, 101동 1203호")도 흔하므로 구분자로
    # 콤마를 허용한다([,\s] = 콤마 또는 공백). 안 그러면 콤마 뒤 동/호가 원문 노출된다(#265).
    r"(?:[,\s]\s*(?P<building>[0-9A-Za-z가-힣]{1,20}(?:아파트|빌라|오피스텔|맨션|타워)))?"
    r"(?:[,\s]\s*(?P<building_dong>\d{1,4}동))?"
    r"(?:[,\s]\s*(?P<building_ho>\d{1,5}호))?"
)

_ADDR_RE = re.compile(
    # 시/도명 뒤: '조사가 아닌 한글'이 공백 없이 붙으면 다른 단어의 일부이므로 제외(#196).
    # 조사(…시에/…시로/…시에서)나 비한글(공백·문장부호·끝)이 오면 시/도만으로도 주소로 인정한다.
    # gu/dong/bunji 뒤에 조사가 붙는 건 원래도 허용된다("...123-4에 거주").
    r"(?P<province>" + _PROVINCE_RE + r")(?!(?!" + _JOSA + r")[가-힣])" + _GU + _GU2 + _TAIL
)

# 시/도 없이 시/군으로 시작하는 주소 — "성남시 분당구 정자동 45-6"(#68).
# 시/도 사전을 시작점으로 삼는 _ADDR_RE는 이런 표기를 통째로 놓쳐 유출된다.
_ADDR_NO_PROVINCE_RE = re.compile(
    # 앞에 한글이 붙으면 다른 단어의 일부이므로 시작점으로 보지 않는다.
    r"(?<![가-힣])(?P<si>[가-힣]{2,9}[시군])"
    # 오탐 억제: 시/군 바로 뒤에 구 또는 동/읍/면/리가 와야만 주소 후보로 인정한다.
    # "성남시로 이사"의 조사 '로'(공백 없음)와 "강남구에서"의 구 단독을 배제한다.
    # 행정동은 숫자가 붙으므로("김포시 사우1동") 동/리 앞 숫자 두 자리까지 허용한다(#423).
    r"(?=\s[가-힣]{1,10}(?:\d{1,2}(?:동|리)|구|동|읍|면|리))" + _GU + _GU2 + _TAIL
)

# 시/도 축약형으로 시작하는 주소 — "서울 강남구 테헤란로 123"(#396).
_ADDR_ABBR_RE = re.compile(
    # 앞에 한글이 붙으면("남서울") 다른 단어의 일부이므로 시작점으로 보지 않는다.
    r"(?<![가-힣])(?P<abbr>" + "|".join(_PROVINCE_ABBR) + r")"
    # 오탐 억제 1단계: 공백 뒤에 시/군/구가 바로 이어져야 후보로 삼는다.
    # "서울 사람", "부산 출신", "경기 침체"처럼 지역 이름으로만 쓰인 문장이 여기서 걸러진다.
    # 2단계(동/읍/면/리·도로명 필수)는 detect()에서 확인한다.
    r"(?=\s[가-힣]{1,10}[시군구])" + _GU + _GU2 + _TAIL
)


def _score(m: re.Match[str], base: float, cap: float) -> float:
    """매칭된 구성 요소가 많을수록 확신도를 높인다(시/군만 vs 동·번지·건물까지)."""
    confidence = base
    if m.group("gu"):
        confidence += 0.15
    if m.groupdict().get("gu2"):
        confidence += 0.05
    if m.group("dong"):
        confidence += 0.15
    if m.group("bunji"):
        confidence += 0.2
    if m.group("building"):
        confidence += 0.15
    return round(min(confidence, cap), 2)


class AddressDetector(Detector):
    """한국 행정구역 주소 탐지기 (시/도 단위부터 번지까지)."""

    kind = "address"

    def detect(self, text: str) -> list[Detection]:
        found: list[Detection] = []
        province_spans: list[tuple[int, int]] = []
        # 시/도 앵커 — 확신도 0.5부터 시작.
        for m in _ADDR_RE.finditer(text):
            province_spans.append((m.start(), m.end()))
            found.append(self._make(m, base=0.5, cap=1.0))
        # 시/도 축약형 앵커(#396) — 정식 시/도명이 없으니 시/군 앵커와 같은 확신도(0.4~)로 둔다.
        # 시/군 앵커보다 먼저 돌려야 "경기 성남시 분당구 …"가 "성남시 분당구 …"로 잘려
        # 두 번 잡히지 않는다. 먼저 잡은 더 넓은 구간을 province_spans에 넣어 뒤에서 중복을 거른다.
        for m in _ADDR_ABBR_RE.finditer(text):
            if not m.group("dong"):
                continue  # "서울 강남구에 산다"처럼 구까지만이면 지역 언급일 뿐 — 유출 아님
            if any(m.start() < end and m.end() > start for start, end in province_spans):
                continue
            province_spans.append((m.start(), m.end()))
            found.append(self._make(m, base=0.4, cap=0.9))
        # 시/군 앵커(시/도 없음) — 확신도 0.4부터. 시/도가 없어 확신이 낮으니 임계값으로 조절 가능.
        for m in _ADDR_NO_PROVINCE_RE.finditer(text):
            if not m.group("dong"):
                continue  # 동/읍/면/리(도로명 포함) 없이 시/군+구만이면 지역 언급일 뿐 — 유출 아님
            if any(m.start() < end and m.end() > start for start, end in province_spans):
                continue  # 시/도 앵커(정식명·축약형) 매칭에 이미 포함된 구간이므로 중복
            found.append(self._make(m, base=0.4, cap=0.9))
        found.sort(key=lambda d: d.start)
        return found

    def _make(self, m: re.Match[str], base: float, cap: float) -> Detection:
        return Detection(
            kind=self.kind,
            start=m.start(),
            end=m.end(),
            text=m.group(0),
            confidence=_score(m, base, cap),
            detector=self.__class__.__name__,
        )
