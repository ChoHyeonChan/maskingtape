"""#603·#674·#676 뒤에도 흔한 문서 문장에서 이름이 새던 다섯 꼴(#685).

1. 쌍점이 붙은 "담당:" 라벨, 2. 이름 뒤 "외 N명"·"등 N명", 3. 뒤 단서(존칭·직함)를 앞 이름들이 나눠 쓰는
나열("김민수, 이서연 님께"), 4. 메신저 대화 내보내기의 "[이름] [오후 3:01]", 5. 판결문 역할어의 복수형
("원고들 김민수, 이서연"). 메일 제목의 "[김민수] 휴가 신청서"는 "[서울시] 보도자료" 같은 말머리와 구별할 단서가
약해 받지 않는다. 입력은 모두 합성이다.
"""

import pytest

from maskingtape.detectors import NameDetector


def _names(text: str) -> list[str]:
    return [text[d.start : d.end] for d in NameDetector().detect(text)]


@pytest.mark.parametrize(
    ("text", "names"),
    [
        # 1. 담당 라벨
        ("담당: 김민수", ["김민수"]),
        ("담당 | 이서연", ["이서연"]),
        ("담당: 박지훈, 최은서", ["박지훈", "최은서"]),
        # 2. 외 N명·등 N명
        ("김민수 외 3명", ["김민수"]),
        ("김민수 등 3명", ["김민수"]),
        ("이서연 외 두 명이 참석했다.", ["이서연"]),
        ("김민수 외 2인", ["김민수"]),
        # 3. 뒤 단서를 나눠 쓰는 나열
        ("김민수, 이서연 님께", ["김민수", "이서연"]),
        ("김민수·이서연 님", ["김민수", "이서연"]),
        ("박지훈, 최은서, 정도윤 님께 보냅니다.", ["박지훈", "최은서", "정도윤"]),
        ("김민수, 이서연 외 2명", ["김민수", "이서연"]),
        ("박지훈, 최은서 대리가 참석했다.", ["박지훈", "최은서"]),
        # 4. 메신저 대화 내보내기
        ("[김민수] [오후 3:01] 자료 확인했습니다", ["김민수"]),
        ("[이서연] [오전 9:15] 네 알겠습니다\n[박지훈] [오전 9:16] 감사합니다", ["이서연", "박지훈"]),
        # 1. 담당 값을 버려도 뒤 나열은 이어받는다
        ("담당: 영업, 김민수", ["김민수"]),
        ("담당: 미정, 김민수", ["김민수"]),
        # 5. 판결문 역할어 복수형
        ("원고들 김민수, 이서연", ["김민수", "이서연"]),
        ("피고들 김민수", ["김민수"]),
        ("피고인들 박지훈, 최은서는 범행을 부인했다.", ["박지훈", "최은서"]),
    ],
)
def test_followup_shapes_are_caught(text: str, names: list[str]) -> None:
    got = _names(text)
    for name in names:
        assert name in got


@pytest.mark.parametrize(
    ("text", "names"),
    [
        # 대조: 지금도 잡히는 꼴은 그대로
        ("담당자: 김민수", ["김민수"]),
        ("담당: 김민수 대리", ["김민수"]),
        ("고객 김민수 외 3명", ["김민수"]),
        ("김민수 님, 이서연 님", ["김민수", "이서연"]),
        ("[김민수 대리] 휴가 신청서", ["김민수"]),
        ("원고 김민수, 이서연", ["김민수", "이서연"]),
    ],
)
def test_existing_cases_unchanged(text: str, names: list[str]) -> None:
    assert sorted(_names(text)) == sorted(names)


@pytest.mark.parametrize(
    "text",
    [
        # 1. 담당 뒤 부서·자리표시 값, 쌍점 없는 담당
        "담당: 영업팀",
        "담당: 마케팅",
        "담당: 미정",
        "담당 부서: 영업팀",
        "담당 지역을 안내합니다.",
        "담당: 풀스택",
        "| 파트 | 담당 | 폴더 |",
        "담당: 정리",
        # 2. 이름이 아닌 말 + 외 N명
        "정원 외 3명을 더 뽑는다.",
        "우리 외 2명이 남았다.",
        "고객 외 2명이 대기 중이다.",
        "이들 외 3명은 귀가했다.",
        "학과 외 2개 기관",
        "임직원 외 30명이 참석했다.",
        "조합원 외 120명이 서명했다.",
        "공무원 등 5명이 다녀갔다.",
        "장애인 등 3명이 이용했다.",
        "이용자 외 5명에게 알렸다.",
        "조문객 외 20명",
        # 4. 말머리 대괄호, 시각 대괄호가 없는 제목
        "[서울시] 보도자료",
        "[하반기] 채용 공고",
        "[공지] 회의 안내",
        "[안내] 일정 변경",
        "[장애] 서버 점검",
        "[이벤트] 당첨자 발표",
        "[공유] 회의 자료",
        "[정정] 공고 내용",
        # 5. 복수형 뒤 일반어
        "원고들의 주장은 이유 없다.",
        "피고들 주장은 받아들이지 않는다.",
        "원고들 주장에 대하여 본다.",
    ],
)
def test_followup_non_names(text: str) -> None:
    assert _names(text) == []


@pytest.mark.parametrize(
    ("text", "names"),
    [
        # 판결문 앞 단서 뒤 역할어 복수형, 그 뒤 나열(교차검토가 찾은 덜 가림). 복수형이 단서가 되기 전에는
        # "원고들"을 이름으로 잡고 뒤 나열을 이어받았다. 단서로 버려도 뒤 이름은 그대로 가린다
        ("증인 원고들, 이서연", ["이서연"]),
        ("증인: 원고들, 이서연", ["이서연"]),
        ("증인 원고들, 김민수, 이서연", ["김민수", "이서연"]),
        ("피고 원고들, 이서연", ["이서연"]),
        ("피고인 원고들, 이서연", ["이서연"]),
        ("신고인 원고들, 이서연", ["이서연"]),
        ("구매자 원고들, 이서연", ["이서연"]),
        ("판사 원고들 총무, 이서연", ["이서연"]),
        # 외 N명 뒤의 조사·어미, 거꾸로 나열의 가운뎃점
        ("김민수 외 3명에게는 안내했다.", ["김민수"]),
        ("김민수 외 3명으로 구성된다.", ["김민수"]),
        ("김민수 등 3명뿐이다.", ["김민수"]),
        ("이서연･김민수 님", ["이서연", "김민수"]),
        ("이서연•김민수 님", ["이서연", "김민수"]),
    ],
)
def test_followup_edge_shapes_are_caught(text: str, names: list[str]) -> None:
    got = _names(text)
    for name in names:
        assert name in got


@pytest.mark.parametrize(
    "text",
    [
        # 담당 뒤 두 글자 업무(교차검토가 찾은 오탐)
        "행사 담당: 심사",
        "식당 담당: 주방",
        "시험 담당: 채점",
        "공연 담당: 조명",
        "급식 담당: 배식",
        "의료봉사 담당: 진료",
        "행사 담당: 장식",
    ],
)
def test_two_char_duty_values_are_not_names(text: str) -> None:
    assert _names(text) == []


def test_surname_with_title_in_reverse_list_masks_only_surname() -> None:
    # "김부장"은 성씨 + 직함이다. 직함은 남기고 성씨만 가린다(#677과 같은 규칙)
    assert sorted(_names("김부장, 이서연 님께 전달했습니다.")) == ["김", "이서연"]


def test_duty_column_in_table_is_not_a_name_column() -> None:
    # 표 머리행의 "담당" 열은 이름 열로 보지 않는다. 성명 열의 이름만 가린다
    assert _names("성명,담당\n김민수,영업") == ["김민수"]


@pytest.mark.parametrize(
    "text",
    [
        # 3. 쉼표 앞이 일반어·부사면 뒤 단서를 이어받지 않는다
        "정보, 이서연 님",
        "참고로, 이서연 님께 전달했습니다.",
        "서울·부산, 이서연 님",
        # 두 글자 칸은 거꾸로 이어받지 않는다(일반어와 겹치는 일이 잦다)
        "오늘, 이서연 님이 오셨다.",
        "진료, 이서연 님 담당",
    ],
)
def test_reverse_list_stops_at_common_words(text: str) -> None:
    assert _names(text) == ["이서연"]
