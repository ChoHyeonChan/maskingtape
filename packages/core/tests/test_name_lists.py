"""라벨 뒤에 나열한 이름 목록 테스트(#602). 모든 이름은 합성(가짜)이다.

라벨(참석자·보호자·담당자 등)은 첫 이름에만 붙어서, 둘째 이름부터는 단서 없는 후보가 되어
버려졌다. 회의록 참석자·결재선·수신인 목록에서 흔한 꼴이다.
"""

import pytest

from maskingtape import Pipeline
from maskingtape.detectors import NameDetector


def names(text: str) -> list[str]:
    return [d.text for d in NameDetector().detect(text)]


@pytest.mark.parametrize(
    "text, expected",
    [
        # 이슈 #602의 다섯 문장
        ("참석자: 김민수, 이서연, 박지훈", ["김민수", "이서연", "박지훈"]),
        ("참석자 김민수·이서연·박지훈", ["김민수", "이서연", "박지훈"]),
        ("참석자: 김민수 이서연 박지훈", ["김민수", "이서연", "박지훈"]),
        ("보호자: 김민수 및 이서연", ["김민수", "이서연"]),
        ("담당자 김민수와 이서연이 참석", ["김민수", "이서연"]),
        # 가운데 이름에 존칭·직함이 붙어도 목록이 끊기지 않는다
        ("참석자: 김민수, 이서연님, 박지훈", ["김민수", "이서연", "박지훈"]),
        ("참석자: 김민수 과장, 이서연 대리, 박지훈", ["김민수", "이서연", "박지훈"]),
        # 맺음말 앞 이름, 두 글자 이름, 슬래시·"그리고"·"하고" 구분
        ("수신인: 김민수, 이서연 귀하", ["김민수", "이서연"]),
        ("참석자: 김민수, 이준", ["김민수", "이준"]),
        ("참석자: 김민수 / 이서연 / 박지훈", ["김민수", "이서연", "박지훈"]),
        ("보호자 김민수 그리고 이서연", ["김민수", "이서연"]),
        ("담당자 김민수하고 이서연이 왔다", ["김민수", "이서연"]),
        # 목록을 닫는 말 앞의 마지막 칸
        ("회의 참석자: 김민수, 이서연, 박지훈 등 3명", ["김민수", "이서연", "박지훈"]),
        ("참석자: 김민수, 이서연 외 2명", ["김민수", "이서연"]),
        # 독립 검증에서 마지막 이름만 새던 끝(괄호 인원, 표 칸, 줄 끝 공백, 인원수)
        ("참석자: 김민수, 이서연, 박지훈 (총 3명)", ["김민수", "이서연", "박지훈"]),
        ("| 참석자 | 김민수, 이서연, 박지훈 |", ["김민수", "이서연", "박지훈"]),
        ("참석자: 김민수, 이서연 ", ["김민수", "이서연"]),
        ("면접자: 김민수, 이서연 2명", ["김민수", "이서연"]),
        # 군·양 존칭, 점 닮은꼴 구분자
        ("학생: 김민수 군, 이서연", ["김민수", "이서연"]),
        (f"참석자 김민수{chr(0x2022)}이서연", ["김민수", "이서연"]),
    ],
)
def test_names_listed_after_a_label_are_all_found(text, expected):
    assert sorted(names(text)) == sorted(expected), names(text)


@pytest.mark.parametrize(
    "text, expected",
    [
        # 목록 뒤 칸이 이름이 아니면 이어받지 않는다
        ("담당자: 김민수, 서울 강남구", ["김민수"]),
        ("참석자: 김민수, 총 3명", ["김민수"]),
        ("참석자: 김민수 외 2명", ["김민수"]),
        ("참석자: 김민수, 이상 없음", ["김민수"]),
        ("작성자: 김민수, 문서 번호 12", ["김민수"]),
        ("담당자: 김민수, 정보보호팀", ["김민수"]),
        ("참석자: 김민수, 차장", ["김민수"]),
        # "라벨: 이름, 다른 칸 라벨 값"(#537) — 쉼표 뒤가 이름 목록이 아니다
        ("전입신고 대상자: 윤은성, 신주소 대구", ["윤은성"]),
        ("성명: 홍길동, 전공 컴퓨터공학", ["홍길동"]),
        ("성명: 홍길동, 지역 서울", ["홍길동"]),
        # 독립 검증에서 찾은 오탐 — 명사+을·를·(으)로, 관계·부서·상태어, "○○과 진료"
        ("환자: 김민수, 진료를 거부함.", ["김민수"]),
        ("담당자 김민수와 공동으로 검토한다.", ["김민수"]),
        ("보호자: 김민수, 남편", ["김민수"]),
        ("담당자: 김민수/홍보팀/010-1234-5678", ["김민수"]),
        ("참석자: 김민수, 홍보팀장", ["김민수"]),
        ("환자: 김민수, 정신과 진료 중.", ["김민수"]),
        ("환자명: 김민수, 진료과: 내과", ["김민수"]),
        # 공백만으로 이어 쓴 칸은 라벨에 쌍점·세로줄이 있고 성+이름 두 자일 때만 받는다
        ("환자 김민수 진료비 청구", ["김민수"]),
        ("담당자 김민수 정리 부탁", ["김민수"]),
        ("참석자: 김민수 진행", ["김민수"]),
        # 줄을 넘지 않는다
        ("고객 김민수\n이서연은 내일", ["김민수"]),
        # 단서 없이 나열한 이름은 지금처럼 잡지 않는다(이 PR의 범위 밖)
        ("김민수, 이서연, 박지훈", []),
    ],
)
def test_list_does_not_spill_into_non_names(text, expected):
    assert sorted(names(text)) == sorted(expected), names(text)


def test_listed_names_are_masked_through_the_pipeline():
    text = "참석자: 김민수, 이서연, 박지훈"
    assert Pipeline().anonymize(text).text == "참석자: ***, ***, ***"


def test_listed_names_respect_min_confidence():
    # 이어받은 이름은 단서 하나짜리와 같은 0.5다 — 안전망을 0.75로 거는 경로에는 섞이지 않는다
    found = NameDetector(min_confidence=0.75).detect("참석자: 김민수, 이서연, 박지훈")
    assert all(d.confidence >= 0.75 for d in found)
