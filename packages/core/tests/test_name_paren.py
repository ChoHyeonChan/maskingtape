"""이름 바로 뒤 괄호에 직함·나이·서명·연락처가 오는 꼴(#604). 모든 이름·번호는 합성(가짜)이다.

명단·계약서 서명란·기사체 문장("김민수(35)")에서 흔한데, 뒤 단서는 이름 바로 뒤의 직함·존칭만
봐서 괄호가 끼면 이름을 통째로 놓쳤다. 전화번호만 가려지고 이름이 남으면 가린 문서가 "이 연락처의
주인"을 그대로 보여 준다.
"""

import pytest

from maskingtape import Pipeline
from maskingtape.detectors import NameDetector


def names(text: str) -> list[str]:
    return [d.text for d in NameDetector().detect(text)]


@pytest.mark.parametrize(
    "text, expected",
    [
        # 이슈 #604의 다섯 문장
        ("김민수(대리)", ["김민수"]),
        ("김민수(35세, 남)", ["김민수"]),
        ("김민수(인)", ["김민수"]),
        ("김민수 (서명)", ["김민수"]),
        ("김민수 (010-1234-5678)", ["김민수"]),
        # 직함·존칭 여러 꼴
        ("최지훈(팀장)이 보고했다.", ["최지훈"]),
        ("김민수(대리, 영업팀)", ["김민수"]),
        ("이서연(팀장님) 참석", ["이서연"]),
        # 나이·성별
        ("이서연(여, 28세)", ["이서연"]),
        ("박지훈(만 35세)", ["박지훈"]),
        ("김민수(35)씨가 검거됐다.", ["김민수"]),
        ("이준(28세)", ["이준"]),
        ("이서연(여)", ["이서연"]),
        # 두 글자 이름도 성별 뒤에 나이가 이어지면 받는다
        ("이준(여, 28세)", ["이준"]),
        ("이준(남/35세)", ["이준"]),
        ("김결(남성, 만 40세)", ["김결"]),
        # 서명 표시
        ("이준(인)", ["이준"]),
        ("김민수 (서명 또는 인)", ["김민수"]),
        ("김민수 (서명 또는 날인)", ["김민수"]),
        ("박지훈(직인)", ["박지훈"]),
        # 연락처
        ("홍길동(hong@example.com)", ["홍길동"]),
        ("김민수(02-555-1234)", ["김민수"]),
        # 앞 단서가 있으면 두 글자 이름도 숫자·연락처 괄호와 함께 받는다(괄호 없이도 앞 단서로 잡히던 꼴)
        ("고객 이준(35)", ["이준"]),
        ("담당자 이준(010-1234-5678)", ["이준"]),
        ("환자 박솔 (02-555-1234)", ["박솔"]),
    ],
)
def test_name_followed_by_parenthesized_cue_is_found(text, expected):
    assert names(text) == expected, names(text)


@pytest.mark.parametrize(
    "text, expected",
    [
        # 괄호용 일반명사 목록은 괄호 하나만 단서일 때만 쓴다. 다른 단서 경로에서 같은 글자로
        # 시작하는 실명을 버리면 예전보다 덜 가린다(#604 검증에서 찾은 회귀).
        ("공정은 씨", ["공정은"]),
        ("담당자 공정은", ["공정은"]),
        ("정정은 님께", ["정정은"]),
        ("고객 임원이", ["임원이"]),
        ("공정은 / 개발팀 / 010-1234-5678", ["공정은"]),
    ],
)
def test_paren_common_words_do_not_drop_names_on_other_cues(text, expected):
    assert names(text) == expected, names(text)


@pytest.mark.parametrize(
    "text",
    [
        # 성씨 글자로 시작하는 일반명사 + 괄호 설명
        "정보(선택)",
        "주소(도로명)",
        "이용(필수)",
        "조건(35세 이상)은 별도",
        # 두 글자 낱말 + 연락처·숫자·성별만 있는 괄호는 세 글자 이름일 때만 받는다
        "문의(02-555-1234)",
        "전화(010-1234-5678)",
        "정원(35)",
        "한우(3)",
        "성인(남)",
        # 서식의 성별 칸·연락처 칸(표적 검사에서 찾은 오탐)
        "구분(남/여)",
        "성별 구분(남, 여)",
        "문의처 (02-555-1234)",
        "임원(남) 3명",
        "정정(인)",
        # 직함만 단서면 세 글자 이름만(기존 규칙과 같다)
        "공정(대리) 업무",
        "조직(팀장) 개편",
        # 앞 직함 + 두 글자 + 서명·숫자 괄호는 앞 직함만 있을 때처럼 세 글자를 요구한다(결재란의 업무어)
        "부장 전결(인)",
        "과장 정리(3)",
        # 괄호 안이 단서 꼴이 아니면 지금처럼 잡지 않는다
        "김민수(가명) 사례",
        "홍길동(2024) 영화",
    ],
)
def test_common_words_before_parentheses_are_not_names(text):
    assert names(text) == [], names(text)


def test_name_and_phone_in_parentheses_are_both_masked():
    # 전화만 가려지고 이름이 남으면 "이 연락처의 주인"이 드러난다
    text = "김민수 (010-1234-5678)"
    assert Pipeline().anonymize(text).text == "*** (*************)"
