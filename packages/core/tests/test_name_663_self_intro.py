"""단서가 자기소개·변경 기록에만 있는 이름(#663 남은 부분, #589).

1. 인사말이나 "저는" 뒤 소속(…팀·…센터·…본부 등) 다음 이름 + "입니다"("안녕하세요. 인사팀 김민수입니다", 메일·상담
녹취의 자기소개). 인사말을 요구해 "검사 결과 정상입니다"·"팀 송년회입니다" 같은 일반 문장은 받지 않는다.
2. "제 이름은 황재고요"처럼 말로 이름을 대는 꼴. 3. 이미 잡힌 이름 뒤 "에서 ○○○(으)로 변경"의 두 번째 이름.
셋 다 이미 찾은 이름에 더하기만 한다. 판결문의 판사·증인 + 두 글자 이름 + 조사(#741)는 "증인 유무를"·"판사 권한은" 같은
일반어와 겹쳐 이번에 넣지 않았다. 입력은 모두 합성이다.
"""

import pytest

from maskingtape.detectors import NameDetector


def _names(text: str) -> list[str]:
    return [text[d.start : d.end] for d in NameDetector().detect(text)]


@pytest.mark.parametrize(
    ("text", "names"),
    [
        # 1. 인사말·"저는" 뒤 소속 + 이름 + 어미
        ("안녕하세요.\n구매팀 백군원입니다.\n요청하신 견적서 보내드립니다.", ["백군원"]),
        ("상담원: 안녕하세요, 고객센터 임인예입니다. 무엇을 도와드릴까요?", ["임인예"]),
        ("안녕하세요. 인사팀 강훈민입니다.", ["강훈민"]),
        ("저는 개발팀 조호윤입니다.", ["조호윤"]),
        ("안녕하세요.\n구매팀 서윤입니다.", ["서윤"]),
        ("상담원: 안녕하세요, 고객센터 문규입니다.", ["문규"]),
        ("감사합니다. 한빛전자 경영지원팀 김민수입니다.", ["김민수"]),
        ("안녕하세요, 품질관리본부 이서연이에요.", ["이서연"]),
        ("여보세요, 고객센터 박지훈입니다", ["박지훈"]),
        ("안녕하십니까.\n\n총무과 최은서입니다.", ["최은서"]),
        # 흔한 어미·끼어드는 역할어·긴 앞말
        ("안녕하세요. 인사팀 김민수인데요.", ["김민수"]),
        ("안녕하세요. 인사팀 김민수라고 합니다.", ["김민수"]),
        ("안녕하세요. 인사팀 김민수입니다만 확인 부탁드립니다.", ["김민수"]),
        ("안녕하세요. 인사팀 담당 김민수입니다.", ["김민수"]),
        ("안녕하세요. 인사팀 파트장 김민수입니다.", ["김민수"]),
        ("안녕하세요. 이번에 새로 합류한 인사팀 김민수입니다.", ["김민수"]),
        ("안녕하세요. (주)한빛 인사팀 김민수입니다.", ["김민수"]),
        ("안녕하세요. 인사팀의 김민수입니다.", ["김민수"]),
        ("안녕하세요. 인사팀 김민수 입니다.", ["김민수"]),
        # 두 글자 이름 뒤 "이"·"라"는 실명 끝 글자일 수 있어 함께 가린다("주한이고요"의 실명이 "주한이"일 때)
        ("안녕하세요, 인사팀 주한이고요.", ["주한이"]),
        ("안녕하세요, 인사팀 서윤이에요.", ["서윤이"]),
        ("안녕하세요. 인사팀 박세라고 합니다.", ["박세라"]),
        ("안녕하세요. 인사부 남궁이이라고 합니다.", ["남궁이이"]),
        # 성씨 + 직함 모양이어도 자기소개 자리에서는 세 글자를 다 가린다("오 수석"일 수도, 실명 "오수석"일 수도 있다)
        ("수고 많으십니다. 총무과 오수석입니다.", ["오수석"]),
        # 2. 제 이름은 ○○고요
        ("고객: 네, 제 이름은 김지재고요, 연락처는 따로 드릴게요.", ["김지재"]),
        ("고객: 제 이름은 황재고요,", ["황재"]),
        ("제 이름은 조정이고요.", ["조정이"]),
        # 기존 "이름" 단서 경로가 잡던 "김하"에 "김하이"를 더한다. Pipeline이 겹친 구간을 합쳐 "김하이"를 가린다.
        ("제 이름은 김하이고요.", ["김하", "김하이"]),
        ("제 이름은 최은서입니다.", ["최은서"]),
        # 3. 변경 기록의 두 번째 이름
        ("담당자가 정규은에서 송빈민으로 변경되었습니다.", ["정규은", "송빈민"]),
        ("담당자가 김민수에서 이서연으로 교체되었습니다.", ["김민수", "이서연"]),
        ("담당자가 김민수에서 박지후로 바뀌었습니다.", ["김민수", "박지후"]),
        ("담당자가 백현에서 안우로 변경되었습니다.", ["백현", "안우"]),
        ("담당자가 김민수에서 이서연으로 최종 변경되었습니다.", ["김민수", "이서연"]),
        ("담당자가 김민수에서\n이서연으로 변경되었습니다.", ["김민수", "이서연"]),
        # 앞이 이름이어도 뒤가 사람이 아닌 상태면 받지 않는다
        ("표시 이름: 김민수에서 공용으로 변경했습니다.", ["김민수"]),
    ],
)
def test_self_intro_and_change_log_names(text: str, names: list[str]) -> None:
    assert _names(text) == names


@pytest.mark.parametrize(
    "text",
    [
        # 소속 뒤 일반어·직함·업무어·문서·행사 명사
        "인사팀 담당입니다.",
        "고객센터 상담원입니다.",
        "안녕하세요. 개발팀 서버입니다.",
        "개발팀 서비스입니다.",
        "인사팀 안내문입니다.",
        "영업팀 공지입니다.",
        "구매팀 신입입니다.",
        "재무팀 전원입니다.",
        "고객센터 정보입니다.",
        "총무팀 공석입니다.",
        "안녕하세요. 총무팀 공지문입니다. 확인 부탁드립니다.",
        "안녕하세요. 인사팀 송년회입니다. 참석 여부를 알려 주세요.",
        "안녕하세요. 재무팀 정산표입니다.",
        "인사팀 정리하고요, 다음 주에 보고드릴게요.",
        "제 이름은 비밀이고요.",
        # 인사말이 없거나 소속이 아닌 말("결과"·"전부"·"화장실")
        "검사 결과 정상입니다.",
        "안녕하세요. 검사결과 정상입니다.",
        "다음 주는 팀 송년회입니다.",
        "안녕하세요. 팀 송년회입니다.",
        "안녕하세요. 우리 팀 송년회입니다.",
        "전부 정상입니다.",
        "안녕하세요. 화장실 고장입니다.",
        "고객센터 박지훈입니다",
        # 판결문 역할어 뒤 두 글자 일반어(#741은 이 때문에 이번에 넣지 않았다)
        "증인 신문은 생략한다.",
        "증인 유무를 확인해 주세요.",
        "판사 권한은 법률로 정한다.",
        "판사 공백이 장기화되고 있다.",
        "검사 결과는 정상이다.",
        # 앞이 이름이 아니면 변경 기록으로 보지 않는다
        "일정이 오전에서 오후로 변경되었습니다.",
        "장소가 서울에서 부산으로 변경되었습니다.",
    ],
)
def test_non_names_stay_unmasked(text: str) -> None:
    assert _names(text) == []


def test_new_shapes_need_low_confidence_mode() -> None:
    """새 꼴은 단서 하나짜리(0.5)다. 앞뒤 단서를 둘 다 요구하는 0.75 모드에서는 더하지 않는다."""
    detector = NameDetector(min_confidence=0.75)
    assert detector.detect("안녕하세요.\n구매팀 백군원입니다.") == []
    assert [d.text for d in detector.detect("담당자가 김민수에서 이서연으로 변경되었습니다.")] == []
